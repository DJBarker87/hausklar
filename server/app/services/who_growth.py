def normal_cdf(z: float) -> float:
    """Standard-normal CDF via the error function (no scipy dependency)."""
    return 0.5 * (1.0 + math.erf(z / math.sqrt(2.0)))


def _table(metric: str) -> dict[str, dict[int, tuple[float, float, float]]]:
    return WEIGHT_FOR_AGE if metric == "weight" else HEIGHT_FOR_AGE


def _lms(metric: str, sex: str | None, month: int) -> tuple[float, float, float] | None:
    if sex not in ("male", "female"):
        return None
    return _table(metric)[sex].get(month)


def _lms_interpolated(
    metric: str, sex: str, age_months: float
) -> tuple[float, float, float] | None:
    """LMS linearly interpolated between the two bounding whole months.

    WHO reference rows are monthly, but weight changes ~1kg in the first month,
    so nearest-month rounding produces wildly different centiles a day apart.
    Interpolating keeps the centile smooth across the newborn window.
    """
    lower_month = int(math.floor(age_months))
    lower = _lms(metric, sex, lower_month)
    if lower is None:
        return None
    fraction = age_months - lower_month
    if fraction <= 0:
        return lower
    upper = _lms(metric, sex, lower_month + 1)
    if upper is None:
        return lower
    return tuple(a + (b - a) * fraction for a, b in zip(lower, upper))


def centile(
    metric: str, sex: str | None, age_months: float | None, value: float | None
) -> float | None:
    """Percentile (0-100) for a measurement, or None when it cannot be computed."""
    if value is None or value <= 0 or age_months is None or sex not in ("male", "female"):
        return None
    if age_months < 0 or age_months > MAX_AGE_MONTHS:
        return None
    lms = _lms_interpolated(metric, sex, age_months)
    if lms is None:
        return None
    length, median, spread = lms
    if length == 0:
        z = math.log(value / median) / spread
    else:
        z = (((value / median) ** length) - 1.0) / (length * spread)
    return round(normal_cdf(z) * 100.0, 1)


def _value_at_z(lms: tuple[float, float, float], z: float) -> float:
    length, median, spread = lms
    if length == 0:
        return median * math.exp(spread * z)
    return median * (1.0 + length * spread * z) ** (1.0 / length)


def reference_curve(metric: str, sex: str | None) -> list[dict]:
    """p2..p98 bands for each whole month 0-60, or [] when sex is unknown."""
    if sex not in ("male", "female"):
        return []
    table = _table(metric)[sex]
    curve: list[dict] = []
    for month in range(MAX_AGE_MONTHS + 1):
        lms = table.get(month)
        if lms is None:
            continue
        point: dict = {"age_months": month}
        for label, z in CENTILE_LINES.items():
            point[label] = round(_value_at_z(lms, z), 2)
        curve.append(point)
    return curve
